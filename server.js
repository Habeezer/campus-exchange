const express = require('express');
const path = require('path');
const multer = require('multer');
const fs = require('fs');

// IMPORT THE DATABASE
const db = require('./database'); 

const app = express();
const PORT = process.env.PORT || 3000;

app.use(express.json());

// Ensure uploads directory exists
if (!fs.existsSync('uploads')) fs.mkdirSync('uploads');

// Multer setup (same as yesterday)
const storage = multer.diskStorage({
  destination: function (req, file, cb) { cb(null, 'uploads/'); },
  filename: function (req, file, cb) {
    const uniqueSuffix = Date.now() + '-' + Math.round(Math.random() * 1E9);
    cb(null, uniqueSuffix + '-' + file.originalname);
  }
});
const upload = multer({ storage: storage });

// --- API ROUTES ---

// 1. GET all listings from the DATABASE
app.get('/api/listings', (req, res) => {
  try {
    // SQL query to get everything
    const listings = db.prepare('SELECT * FROM listings').all();
    res.json(listings);
  } catch (error) {
    res.status(500).json({ error: "Failed to fetch listings" });
  }
});

// 2. POST a new listing to the DATABASE
app.post('/api/listings', upload.single('image'), (req, res) => {
  try {
    // Handle the image path
    const imagePath = req.file ? `/uploads/${req.file.filename}` : "https://images.unsplash.com/photo-1532012197267-da84d127e765?w=400&q=80";

    // SQL query to insert data
    const insert = db.prepare(`
      INSERT INTO listings (title, price, category, condition, image) 
      VALUES (?, ?, ?, ?, ?)
    `);

    // Run the query with the data
    const info = insert.run(
      req.body.title,
      req.body.price,
      req.body.category,
      req.body.condition,
      imagePath
    );

    res.status(201).json({ 
      message: "Listing created", 
      id: info.lastInsertRowid // This gives us the new ID generated by SQL
    });
  } catch (error) {
    console.error(error);
    res.status(500).json({ error: "Failed to create listing" });
  }
});

// Serve static files
app.use('/uploads', express.static(path.join(__dirname, 'uploads')));
app.use(express.static(path.join(__dirname, 'public')));

app.listen(PORT, () => {
  console.log(`Campus Exchange running at http://localhost:${PORT}`);
});